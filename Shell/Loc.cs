        // читает lang из файла настроек до создания окна
        public static void Init(string settingsPath)
        {
            string lang = "";
            try
            {
                if (File.Exists(settingsPath))
                    foreach (string raw in File.ReadAllLines(settingsPath, Encoding.UTF8))
                    {
                        string l = raw.Trim();
                        if (l.StartsWith("lang=", StringComparison.OrdinalIgnoreCase)) { lang = l.Substring(5).Trim().ToLowerInvariant(); break; }
                    }
            }
            catch { }
            if (lang.Length == 0)
                lang = System.Globalization.CultureInfo.CurrentUICulture.TwoLetterISOLanguageName == "ru" ? "ru" : "en";
            En = lang == "en";
            if (En) Fill();
        }

        public static string T(string ru)
        {
            if (!En || ru == null || ru.Length == 0) return ru;
            string e;
            return d.TryGetValue(ru, out e) ? e : ru;
        }

